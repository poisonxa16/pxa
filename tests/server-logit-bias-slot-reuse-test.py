#!/usr/bin/env python3
"""A request's logit_bias / ignore_eos must not leak into the next request on the same slot (public pxa #9).

The server keeps one sampling-parameter set per slot across requests. Before the fix the logit_bias
block only cleared it when the new request carried its own logit_bias, so a request with
ignore_eos=true (EOS = -inf) or a logit_bias left that bias on the slot, and every later request on
the slot that did not set them inherited it: EOS stayed suppressed and replies ran to the token limit.

Checks, each decided from what the server itself reports (GET /slots, the /completion body):

  leak     -np 1. A = ignore_eos + a logit_bias; B = neither. After B the slot must report
           ignore_eos=false and an empty logit_bias, and B's body must equal B's body on a freshly
           booted server (temperature 0, cache_prompt off). Before the fix: ignore_eos=true and A's
           bias on B.
  replace  -np 1. A = logit_bias {t1}; B = logit_bias {t2}: B's slot must carry t2 only.
  default  server booted with --ignore-eos: a request that sets nothing keeps the server's EOS ban
           (the reset goes to the server's defaults, not to an empty bias), also after a request
           that set its own logit_bias.

Any GGUF works (random-weight fixtures included: when the generated bytes are not valid UTF-8 the
body is the server's encoder error, which is still a deterministic function of the stream). When the
engine refuses the model at boot with "<arch> needs -fa off and -mla 1 for now" (the GLM tiny fixture
the merge passes use), the harness boots again once with exactly the flags the engine named and says
so: those flags do not touch the slot sampling state under test.

usage: server-logit-bias-slot-reuse-test.py --server BIN --model GGUF [--port 18410] [--out DIR]
                                            [--threads 4] [--extra "<more server flags>"]
exit 0 = all checks pass, 1 = a check failed, 2 = the harness could not run.
"""
import argparse, hashlib, json, os, re, shlex, subprocess, sys, time, urllib.request, urllib.error

PROMPT = "The capital of France is"
BIAS_TOK_A = 11     # arbitrary in-vocab token ids for the bias entries
BIAS_TOK_B = 13


def ldpath(b):
    d = os.path.dirname(os.path.abspath(b)); r = os.path.dirname(d)
    return ":".join([d, os.path.join(r, "src"), os.path.join(r, "ggml", "src")])


REFUSAL = re.compile(r"needs ((?:-{1,2}[A-Za-z][\w-]* [\w.-]+)(?: and -{1,2}[A-Za-z][\w-]* [\w.-]+)*) for now")


def boot_refusal(log):
    """-> (flags the engine named, the line) when the server refused the model's defaults at boot, else ([], the last error-ish line)."""
    try:
        lines = open(log, errors="replace").read().splitlines()
    except OSError:
        return [], ""
    for ln in lines:
        m = REFUSAL.search(ln)
        if m:
            return [w for part in m.group(1).split(" and ") for w in shlex.split(part)], ln.strip()
    errs = [ln.strip() for ln in lines if re.search(r"error|failed|unable", ln, re.I)]
    return [], (errs[-1] if errs else (lines[-1].strip() if lines else ""))


class Server:
    def __init__(self, a, extra, log):
        self.port = a.port
        env = dict(os.environ); env["LD_LIBRARY_PATH"] = ldpath(a.server) + ":" + env.get("LD_LIBRARY_PATH", "")
        cmd = [a.server, "-m", a.model, "-ngl", "0", "-c", "512", "-t", str(a.threads), "-np", "1",
               "--host", "127.0.0.1", "--port", str(a.port)] + shlex.split(a.extra) + a.arch_flags + extra
        self.logf = open(log, "w")
        self.p = subprocess.Popen(cmd, env=env, stdout=self.logf, stderr=subprocess.STDOUT)
        t0 = time.time()
        while time.time() - t0 < 300:
            if self.p.poll() is not None:
                self.logf.close()
                flags, why = boot_refusal(log)
                if flags and not a.arch_flags:
                    a.arch_flags = flags
                    print(f"NOTE the engine refused the model's defaults ({why}); booting with {' '.join(flags)} from here on")
                    self.__init__(a, extra, log); return
                raise RuntimeError(f"server died during boot ({why}); see {log}")
            try:
                urllib.request.urlopen(f"http://127.0.0.1:{a.port}/health", timeout=5); return
            except Exception:
                time.sleep(0.5)
        raise RuntimeError(f"server never came up; see {log}")

    def completion(self, extra):
        body = {"prompt": PROMPT, "n_predict": 6, "temperature": 0.0, "cache_prompt": False, "seed": 1}
        body.update(extra)
        req = urllib.request.Request(f"http://127.0.0.1:{self.port}/completion", data=json.dumps(body).encode(),
                                     headers={"Content-Type": "application/json"})
        try:
            raw = urllib.request.urlopen(req, timeout=600).read()
        except urllib.error.HTTPError as e:
            raw = e.read()
        try:
            o = json.loads(raw)
            key = json.dumps({"content": o.get("content"), "tokens_predicted": o.get("tokens_predicted")}, sort_keys=True)
        except Exception:
            key = raw.decode("utf-8", "replace")
        return hashlib.sha256(key.encode()).hexdigest()[:16]

    def slot(self):
        raw = urllib.request.urlopen(f"http://127.0.0.1:{self.port}/slots", timeout=60).read()
        s = json.loads(raw)[0]
        lb = s.get("logit_bias")
        # nlohmann serialises the std::map<llama_token, float> as [[tok, bias], ...]
        toks = sorted(int(e[0]) for e in lb) if isinstance(lb, list) else sorted(int(k) for k in (lb or {}))
        return bool(s.get("ignore_eos")), toks

    def stop(self):
        self.p.terminate()
        try: self.p.wait(30)
        except Exception: self.p.kill()
        self.logf.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", required=True); ap.add_argument("--model", required=True)
    ap.add_argument("--port", type=int, default=18410); ap.add_argument("--out", default=".")
    ap.add_argument("--threads", type=int, default=4); ap.add_argument("--extra", default="")
    a = ap.parse_args(); os.makedirs(a.out, exist_ok=True); a.arch_flags = []
    fails = []

    def check(name, ok, detail):
        print(f"{'PASS' if ok else 'FAIL'} {name}: {detail}"); (None if ok else fails.append(name))

    A = {"ignore_eos": True, "logit_bias": [[BIAS_TOK_A, -5.0]]}
    try:
        # reference: B on a fresh server
        s = Server(a, [], os.path.join(a.out, "ref.log"))
        ref_b = s.completion({}); ref_slot = s.slot(); s.stop()

        s = Server(a, [], os.path.join(a.out, "leak.log"))
        s.completion(A); slot_a = s.slot()
        b = s.completion({}); slot_b = s.slot()
        s.completion({"logit_bias": [[BIAS_TOK_A, 2.0]]})
        s.completion({"logit_bias": [[BIAS_TOK_B, 2.0]]}); slot_r = s.slot()
        s.stop()

        s = Server(a, ["--ignore-eos"], os.path.join(a.out, "default.log"))
        s.completion({}); slot_d1 = s.slot()
        s.completion({"logit_bias": [[BIAS_TOK_A, -5.0]]}); slot_d2 = s.slot()
        s.completion({}); slot_d3 = s.slot()
        s.stop()
    except Exception as e:
        print(f"HARNESS {e}"); return 2

    check("leak/a-applied", slot_a[0] and BIAS_TOK_A in slot_a[1], f"A slot ignore_eos={slot_a[0]} bias={slot_a[1]}")
    check("leak/b-settings", slot_b == ref_slot, f"B after A: ignore_eos={slot_b[0]} bias={slot_b[1]}; fresh: {ref_slot}")
    check("leak/b-output", b == ref_b, f"B after A body {b} vs fresh {ref_b}")
    check("replace", slot_r[1] == [BIAS_TOK_B] and not slot_r[0], f"after {{t{BIAS_TOK_A}}} then {{t{BIAS_TOK_B}}}: {slot_r}")
    check("default/kept", slot_d1[0], f"--ignore-eos server, empty request: ignore_eos={slot_d1[0]} bias={slot_d1[1]}")
    check("default/restored", slot_d3 == slot_d1, f"after a request with its own bias {slot_d2}: {slot_d3} vs {slot_d1}")
    print("RESULT", "PASS" if not fails else "FAIL " + ",".join(fails))
    return 0 if not fails else 1


if __name__ == "__main__":
    sys.exit(main())
